/** ARENA03A: private save transition. No HTTP, clock read or database write.
 * The caller must own the save lock, read PostgreSQL time and certify the duel.
 * Never accept a balance, reward, result or team from a public request.
 */
import {arenaFloorPoints,arenaWeeklyProjection,startArenaRun,abandonArenaRun,settleCertifiedArenaFloor} from './weeklyArena.js';
import type {ArenaWeeklyProgress} from './weeklyArena.js';
import {arenaOpponentLevel,weeklyArenaRotation} from './weeklyArenaRotation.js';
import {prepareRewardJournal} from '../legacy/rewardEvents.js';
import {canonicalOnlineGymTrainerBonuses,canonicalOnlineOwnedCombatant} from '../combat/serverGymPreparation.js';
import {grantXp,battleTrainerXp} from './xp.js';
import {battleProgressFactor,scaledRegionalReward} from '../rewards/regionProgression.js';

export interface ArenaSaveV1 {
 readonly version:1;
 readonly balance:number;
 readonly progress:ArenaWeeklyProgress;
}
const natural=(n:unknown):n is number=>typeof n==='number'&&Number.isSafeInteger(n)&&n>=0;
function checked(raw:string,nowMs:number){
 if(!prepareRewardJournal(raw))return null;
 const source=JSON.parse(raw);
 if(source.mode!=='normal')return null;
 const existing=source.weeklyArena;
 if(existing!==undefined&&(!existing||typeof existing!=='object'||Array.isArray(existing)||
   Object.keys(existing).sort().join(',')!=='balance,progress,version'||existing.version!==1||
   !natural(existing.balance)||!existing.progress))return null;
 const prior:ArenaWeeklyProgress|null=existing===undefined?null:existing.progress;
 const view=arenaWeeklyProjection(nowMs,prior);
 if(!view)return null;
 const busy=source.expedition!==null||source.pendingBattle!=null||source.gymSession!=null||
  source.lastBattle?.captureStatus==='available'||source.pendingRegionalLoot!=null||source.pendingExpeditionLoot!=null;
 return {source,prior,view,balance:existing===undefined?0:existing.balance as number,busy};
}
type Checked=NonNullable<ReturnType<typeof checked>>;
function store(c:Checked,next:ArenaWeeklyProgress,balance=c.balance){
 const arena:ArenaSaveV1={version:1,balance,progress:next};
 c.source.weeklyArena=arena;
 return JSON.stringify(c.source);
}
function validTeam(c:Checked,team:readonly number[]){
 const bonuses=canonicalOnlineGymTrainerBonuses(c.source);
 return !!bonuses&&team.length===3&&c.source.team.length===3&&
  team.every((uid,i)=>uid===c.source.team[i]&&
   !!canonicalOnlineOwnedCombatant(c.source,c.source.roster.find((p:{uid:number})=>p.uid===uid),bonuses));
}
export function onlineArenaProgress(raw:string,nowMs:number){
 const c=checked(raw,nowMs);if(!c)return null;
 return {...c.view,balance:c.balance,busy:c.busy,teamEligible:validTeam(c,c.source.team)};
}
/** runId is generated by the server. Team always derives from the save. */
export function startOnlineArenaRun(raw:string,nowMs:number,runId:string){
 const c=checked(raw,nowMs);if(!c)return {status:'invalid-save'} as const;
 if(c.busy)return {status:'busy'} as const;
 if(!validTeam(c,c.source.team))return {status:'invalid-team'} as const;
 const q=startArenaRun(nowMs,c.prior,runId,c.source.team);
 if(q.status!=='ok')return q;
 return {status:'ok',raw:store(c,q.next),balance:c.balance,progress:q.next} as const;
}
export function abandonOnlineArenaRun(raw:string,nowMs:number,runId:string){
 const c=checked(raw,nowMs);if(!c)return {status:'invalid-save'} as const;
 const q=abandonArenaRun(nowMs,c.prior,runId);
 if(q.status!=='ok')return q;
 return {status:'ok',raw:store(c,q.next),balance:c.balance,progress:q.next} as const;
}
/** Initial reward proposal uses ordinary regional base amounts once per floor
 * per week and the existing overlevel factor. Points ignore that factor.
 * No affinity, capture, badge, ordinary battle counter or item grants.
 */
export function arenaFirstClearRewards(level:number,opponentLevel:number){
 const factor=battleProgressFactor(level,opponentLevel);
 return {coins:scaledRegionalReward(25+opponentLevel*3,factor),
  trainerXp:scaledRegionalReward(battleTrainerXp(opponentLevel),factor),
  pokemonXp:scaledRegionalReward(20+opponentLevel*6,factor)};
}
/** PRIVATE: only the server-resolved outcome can reach this reducer.
 * The writer commits points, XP, gold and action receipt in one transaction.
 */
export function applyCertifiedOnlineArenaResult(raw:string,nowMs:number,weekStartMs:number,
 runId:string,floor:number,uid:number,outcome:'win'|'loss'|'draw'){
 const c=checked(raw,nowMs);if(!c)return {status:'invalid-save'} as const;
 if(c.busy)return {status:'busy'} as const;
 const q=settleCertifiedArenaFloor(nowMs,c.prior,weekStartMs,runId,floor,uid,outcome);
 if(q.status!=='ok')return q;
 if(!c.view.run||!validTeam(c,c.view.run.team))return {status:'invalid-team'} as const;
 const pokemon=c.source.roster.find((p:{uid:number})=>p.uid===uid);
 const level=arenaOpponentLevel(floor);
 if(!pokemon||level===null)return {status:'invalid-save'} as const;
 const reward=q.rewardEligible?arenaFirstClearRewards(pokemon.level,level):{coins:0,trainerXp:0,pokemonXp:0};
 const balance=c.balance+q.points;
 if(!natural(balance)||!natural(c.source.coins+reward.coins)||
  !natural(c.source.trainer.xp+reward.trainerXp)||!natural(pokemon.xp+reward.pokemonXp))
  return {status:'overflow'} as const;
 if(q.rewardEligible){
  const trainer=grantXp('trainer',{level:c.source.trainer.level,xp:c.source.trainer.xp},reward.trainerXp);
  const active=grantXp('pokemon',{level:pokemon.level,xp:pokemon.xp},reward.pokemonXp);
  c.source.trainer.level=trainer.level;c.source.trainer.xp=trainer.xp;
  pokemon.level=active.level;pokemon.xp=active.xp;
  c.source.coins+=reward.coins;
 }
 const next=store(c,q.next,balance);
 if(!prepareRewardJournal(next))return {status:'invalid-save'} as const;
 return {status:'ok',raw:next,balance,progress:q.next,points:q.points,rewardEligible:q.rewardEligible,
  reward,outcome:q.outcome} as const;
}

/** Public-safe projection for future authenticated HTTP. Opponent stats,
 * move ranks, private seed and full engine snapshots are not returned.
 */
export function onlineArenaPublicProjection(raw:string,nowMs:number){
 const c=checked(raw,nowMs);if(!c)return null;
 const rotation=weeklyArenaRotation(c.view.startMs);if(!rotation)return null;
 const team=c.view.run?.team??c.source.team;
 return {...c.view,balance:c.balance,busy:c.busy,teamEligible:validTeam(c,c.source.team),
  rotationVersion:rotation.version,
  team:team.flatMap((uid:number)=>{
   const p=c.source.roster.find((p:{uid:number})=>p.uid===uid);
   return p?[{uid:p.uid,speciesId:p.pokemonId,level:p.level,...(p.megaForm?{megaForm:p.megaForm}:{})}]:[];
  }),
  opponents:rotation.opponents.map(p=>({floor:p.floor,speciesId:p.speciesId,name:p.name,level:p.level,
   guardian:p.guardian,types:p.types,tmIds:p.tmIds,points:arenaFloorPoints(p.floor),
   paid:p.floor<=c.view.paidThrough}))
 };
}
