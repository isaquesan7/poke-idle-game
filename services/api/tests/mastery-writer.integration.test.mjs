import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import pg from 'pg';
import {firstSave} from '../src/initialAdventure.mjs';
import {loadCombatAdapter} from '../src/battlePreview.mjs';
import {writeMastery} from '../src/masteryWriter.mjs';
import {applyExpeditionCommand} from '../src/expeditionWriter.mjs';
import {reserveEncounter} from '../src/encounterReservation.mjs';
test('Mastery: protected atomic sends, persistent favorites, revision and retry',async()=>{
 const db=new URL(process.env.DATABASE_URL);
 assert.equal(db.protocol,'postgresql:');assert.equal(db.hostname,'127.0.0.1');assert.equal(db.port,'55432');
 assert.equal(db.pathname,'/kanto_ci');assert.equal(db.username,'kanto_ci');assert.equal(db.search,'');
 const pool=new pg.Pool({connectionString:db.href});let id;
 try{
  id=(await pool.query("INSERT INTO game_accounts(email,password_hash,email_verified_at) VALUES($1,$2,now()) RETURNING id",['mastery-'+randomUUID()+'@example.test','x'.repeat(48)])).rows[0].id;
  const save=firstSave('Mastery CI',4,1740000000000),raw=JSON.parse(save.journal.raw);
  for(let uid=2;uid<=5;uid++)raw.roster.push({...structuredClone(raw.roster[0]),uid});
  raw.nextUid=6;save.journal.raw=JSON.stringify(raw);
  await pool.query('INSERT INTO game_saves(account_id,schema_version,revision,state) VALUES($1,2,0,$2::jsonb)',[id,JSON.stringify(save)]);
  const write=(command,expectedRevision,actionId=randomUUID())=>writeMastery(pool,{accountId:id,actionId,expectedRevision,command});
  const read=async()=>{const row=(await pool.query('SELECT revision,state FROM game_saves WHERE account_id=$1',[id])).rows[0];return {revision:Number(row.revision),raw:JSON.parse(row.state.journal.raw)};};
  const core=await loadCombatAdapter();
  assert.equal(core.onlineMasteryProjection(save.journal.raw).totalSent,0);
  assert.equal((await write({kind:'send',uids:[1]},0)).status,'protected');
  assert.equal((await write({kind:'send',uids:[2,99]},0)).status,'missing-pokemon');
  assert.equal((await write({kind:'send',uids:[2],points:100},0)).status,'invalid');
  assert.deepEqual((await read()).raw,raw);
  assert.equal((await write({kind:'favorite',uid:2,favorite:true},0)).status,'applied');
  assert.equal((await write({kind:'send',uids:[2,3]},1)).status,'protected');
  const action=randomUUID(),race=await Promise.all([write({kind:'send',uids:[3,4]},1,action),write({kind:'send',uids:[3,4]},1,action)]);
  assert.deepEqual(race.map(r=>r.status).sort(),['applied','duplicate']);
  const after=await read();assert.equal(after.revision,2);
  assert.deepEqual(after.raw.roster.map(p=>p.uid),[1,2,5]);
  assert.equal(after.raw.nextUid,6);assert.deepEqual(after.raw.team,raw.team);assert.deepEqual(after.raw.caughtSpecies,raw.caughtSpecies);
  assert.equal(after.raw.research.totalSent,2);assert.equal(after.raw.research.points['4'],6);
  assert.equal(after.raw.research.history.length,1);assert.equal(after.raw.research.history[0].items.length,2);
  const view=core.onlineMasteryProjection(JSON.stringify(after.raw));
  assert.equal(view.families[0].current.rank,1);assert.equal(view.pokemon.find(p=>p.uid===2).favorite,true);
  assert.equal((await write({kind:'send',uids:[5]},1)).status,'stale');
  assert.equal((await write({kind:'favorite',uid:2,favorite:false},2)).status,'applied');
  assert.equal((await write({kind:'send',uids:[2]},3)).status,'applied');
  assert.equal((await write({kind:'send',uids:[5]},4)).status,'applied');
  assert.equal((await write({kind:'send',uids:[1]},5)).status,'protected');
  const final=await read();assert.equal(final.raw.research.totalSent,4);assert.equal(final.raw.research.points['4'],12);
  assert.equal(final.raw.nextUid,6);assert.equal(final.raw.roster.length,1);
  assert.equal((await applyExpeditionCommand(pool,{accountId:id,actionId:randomUUID(),kind:'start',regionId:1,expectedRevision:5})).status,'applied');
  assert.equal((await write({kind:'favorite',uid:1,favorite:true},6)).status,'busy');
  assert.equal((await applyExpeditionCommand(pool,{accountId:id,actionId:randomUUID(),kind:'stop',expectedRevision:6})).status,'applied');
  assert.equal((await reserveEncounter(pool,{accountId:id,actionId:randomUUID(),regionId:1,expectedRevision:7})).status,'reserved');
  assert.equal((await write({kind:'favorite',uid:1,favorite:true},8)).status,'busy');
  const receipt=await pool.query("SELECT count(*)::int AS n FROM game_action_receipts WHERE account_id=$1 AND kind='mastery-research-send'",[id]);
  assert.equal(receipt.rows[0].n,3);
 }finally{if(id)await pool.query('DELETE FROM game_accounts WHERE id=$1',[id]);await pool.end();}
});
