import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import pg from 'pg';
import {firstSave} from '../src/initialAdventure.mjs';
import {upgradePokemonMove} from '../src/pokemonMoveRankWriter.mjs';
import {equipPokemonMoves} from '../src/pokemonMoveEquipment.mjs';
import {loadCombatAdapter} from '../src/battlePreview.mjs';
import {buildBattleSnapshot} from '../src/battlePreparation.mjs';
import {reserveEncounter} from '../src/encounterReservation.mjs';
test('23F12B3: one rank receipt, UID isolation, frozen ranks and no refund when unequipped',async()=>{
 const db=new URL(process.env.DATABASE_URL);
 assert.equal(db.protocol,'postgresql:');assert.equal(db.hostname,'127.0.0.1');assert.equal(db.port,'55432');
 assert.equal(db.pathname,'/kanto_ci');assert.equal(db.username,'kanto_ci');assert.equal(db.search,'');
 const pool=new pg.Pool({connectionString:db.href});let id;
 try{
  id=(await pool.query("INSERT INTO game_accounts(email,password_hash,email_verified_at) VALUES($1,$2,now()) RETURNING id",['rank-'+randomUUID()+'@example.test','x'.repeat(48)])).rows[0].id;
  const save=firstSave('Rank CI',4,1740000000000);
  await pool.query('INSERT INTO game_saves(account_id,schema_version,revision,state) VALUES($1,2,0,$2::jsonb)',[id,JSON.stringify(save)]);
  const rank=(pokemonUid,moveName,expectedRevision,extra={})=>upgradePokemonMove(pool,{accountId:id,actionId:randomUUID(),pokemonUid,moveName,expectedRevision,...extra});
  const read=async()=>{const r=(await pool.query('SELECT revision,state FROM game_saves WHERE account_id=$1',[id])).rows[0];return {revision:Number(r.revision),save:r.state,raw:JSON.parse(r.state.journal.raw)};};
  assert.equal((await rank(1,'scratch',0)).status,'unavailable');
  assert.equal((await rank(99,'scratch',0)).status,'missing-pokemon');
  assert.equal((await rank(1,'scratch',0,{power:999})).status,'invalid');
  const fixture=await read();Object.assign(fixture.raw.roster[0],{level:20,equippedMoveNames:['scratch','ember','growl']});
  fixture.raw.roster.push({...structuredClone(fixture.raw.roster[0]),uid:2},{...structuredClone(fixture.raw.roster[0]),uid:3});
  fixture.raw.team=[1,2,3];fixture.raw.nextUid=4;fixture.save.journal.raw=JSON.stringify(fixture.raw);
  await pool.query('UPDATE game_saves SET state=$2::jsonb WHERE account_id=$1',[id,JSON.stringify(fixture.save)]);
  assert.equal((await rank(1,'growl',0)).status,'illegal-move');
  assert.equal((await rank(1,'hyper-beam',0)).status,'illegal-move');
  const actionId=randomUUID();
  const race=await Promise.all([rank(1,'ember',0,{actionId}),rank(1,'ember',0,{actionId})]);
  assert.deepEqual(race.map(r=>r.status).sort(),['duplicate','upgraded']);
  assert.equal(race.find(r=>r.status==='upgraded').remaining,3);
  const current=await read();const expected=structuredClone(fixture.raw);expected.roster[0].upgrades={ember:1};
  assert.equal(current.revision,1);assert.deepEqual(current.raw,expected);
  assert.equal((await rank(1,'scratch',0)).status,'stale');
  const core=await loadCombatAdapter();
  const snapshot=buildBattleSnapshot(current.save,{regionId:1,speciesId:10,level:10});
  assert.deepEqual(core.canonicalFrozenCombatants(snapshot).player.ranks,{scratch:0,ember:1,growl:0});
  assert.deepEqual(core.canonicalOnlineGymPreparation(current.raw).player[0].combatant.ranks,{scratch:0,ember:1,growl:0});
  assert.equal((await equipPokemonMoves(pool,{accountId:id,actionId:randomUUID(),expectedRevision:1,pokemonUid:1,moveNames:['scratch','growl']})).status,'equipped');
  assert.equal((await rank(1,'ember',2)).status,'illegal-move');
  const unequipped=await read();assert.deepEqual(unequipped.raw.roster[0].upgrades,{ember:1});
  assert.equal(core.onlineMoveProjection(unequipped.save.journal.raw).pokemon[0].remaining,3);
  assert.equal((await rank(1,'scratch',2)).status,'upgraded');
  assert.equal((await rank(1,'scratch',3)).status,'upgraded');
  assert.equal((await rank(1,'scratch',4)).status,'upgraded');
  assert.equal((await rank(1,'scratch',5)).status,'unavailable');
  assert.equal((await reserveEncounter(pool,{accountId:id,actionId:randomUUID(),regionId:1,expectedRevision:5})).status,'reserved');
  assert.equal((await rank(2,'scratch',6)).status,'busy');
  const count=await pool.query("SELECT count(*)::int AS n FROM game_action_receipts WHERE account_id=$1 AND kind='pokemon-move-rank'",[id]);
  assert.equal(count.rows[0].n,4);
 }finally{if(id)await pool.query('DELETE FROM game_accounts WHERE id=$1',[id]);await pool.end();}
});
