import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import pg from 'pg';
import {firstSave} from '../src/initialAdventure.mjs';
import {trainPokemon} from '../src/pokemonTrainingWriter.mjs';
import {loadCombatAdapter} from '../src/battlePreview.mjs';
import {buildBattleSnapshot} from '../src/battlePreparation.mjs';
import {reserveEncounter} from '../src/encounterReservation.mjs';
import {applyExpeditionCommand} from '../src/expeditionWriter.mjs';
test('23F12A: atomic UID training, D056 budget, battle compatibility and activity locks',async()=>{
 const db=new URL(process.env.DATABASE_URL);
 assert.equal(db.protocol,'postgresql:');assert.equal(db.hostname,'127.0.0.1');assert.equal(db.port,'55432');
 assert.equal(db.pathname,'/kanto_ci');assert.equal(db.username,'kanto_ci');assert.equal(db.search,'');
 const pool=new pg.Pool({connectionString:db.href});let id;
 try{
  id=(await pool.query("INSERT INTO game_accounts(email,password_hash,email_verified_at) VALUES($1,$2,now()) RETURNING id",['training-'+randomUUID()+'@example.test','x'.repeat(48)])).rows[0].id;
  const save=firstSave('Training CI',4,1740000000000);
  await pool.query('INSERT INTO game_saves(account_id,schema_version,revision,state) VALUES($1,2,0,$2::jsonb)',[id,JSON.stringify(save)]);
  const train=(pokemonUid,increments,expectedRevision,extra={})=>trainPokemon(pool,{accountId:id,actionId:randomUUID(),pokemonUid,increments,expectedRevision,...extra});
  const read=async()=>{const r=(await pool.query('SELECT revision,state FROM game_saves WHERE account_id=$1',[id])).rows[0];return {revision:Number(r.revision),save:r.state,raw:JSON.parse(r.state.journal.raw)};};
  assert.equal((await train(1,{hp:1},0)).status,'unavailable');
  assert.equal((await train(99,{hp:1},0)).status,'missing-pokemon');
  assert.equal((await train(1,{hp:-1},0)).status,'invalid');
  assert.equal((await train(1,{damage:10},0)).status,'invalid');
  assert.equal((await train(1,{hp:1},0,{level:100})).status,'invalid');
  const fixture=await read();
  fixture.raw.roster[0].level=50;
  fixture.raw.roster.push({...structuredClone(fixture.raw.roster[0]),uid:2},{...structuredClone(fixture.raw.roster[0]),uid:3});
  fixture.raw.nextUid=4;fixture.raw.team=[1,2,3];
  fixture.save.journal.raw=JSON.stringify(fixture.raw);
  await pool.query('UPDATE game_saves SET state=$2::jsonb WHERE account_id=$1',[id,JSON.stringify(fixture.save)]);
  assert.equal((await train(1,{attack:98,hp:1},0)).status,'unavailable');
  assert.deepEqual((await read()).raw,fixture.raw);
  const actionId=randomUUID();
  const race=await Promise.all([train(1,{attack:60,hp:38},0,{actionId}),train(1,{attack:60,hp:38},0,{actionId})]);
  assert.deepEqual(race.map(r=>r.status).sort(),['duplicate','trained']);
  assert.equal(race.find(r=>r.status==='trained').remaining,0);
  const trained=await read();assert.equal(trained.revision,1);
  const expected=structuredClone(fixture.raw);Object.assign(expected.roster[0].manual,{attack:60,hp:38});
  assert.deepEqual(trained.raw,expected);
  assert.equal((await train(1,{speed:1},1)).status,'unavailable');
  assert.equal((await train(2,{hp:1},0)).status,'stale');
  const core=await loadCombatAdapter();
  const snap=buildBattleSnapshot(trained.save,{regionId:1,speciesId:16,level:3});
  assert.equal(snap.activePokemon.manual.attack,60);
  assert.ok(core.canonicalFrozenCombatants(snap));
  assert.ok(core.canonicalOnlineGymPreparation(trained.raw));
  const invalid=structuredClone(trained.raw);invalid.trainer.level=50;invalid.trainer.manual.attack=41;
  assert.equal(core.canonicalOnlineGymPreparation(invalid),null);
  const invalidSnap=structuredClone(snap);invalidSnap.trainer.level=50;invalidSnap.trainer.manual.attack=41;
  assert.equal(core.canonicalFrozenCombatants(invalidSnap),null);
  const invalidBudget=structuredClone(snap);invalidBudget.activePokemon.manual.speed=1;
  assert.equal(core.canonicalFrozenCombatants(invalidBudget),null);
  assert.equal((await train(1,{hp:1},1,{reset:true})).status,'unavailable');
  const resetId=randomUUID();
  const resets=await Promise.all([train(1,{},1,{reset:true,actionId:resetId}),train(1,{},1,{reset:true,actionId:resetId})]);
  assert.deepEqual(resets.map(r=>r.status).sort(),['duplicate','trained']);
  const reset=await read();assert.equal(reset.revision,2);assert.deepEqual(reset.raw,fixture.raw);
  assert.equal(core.onlinePokemonTrainingProjection(reset.save.journal.raw).pokemon[0].remaining,98);
  assert.equal((await train(1,{},2,{reset:true})).status,'unavailable');
  assert.equal((await applyExpeditionCommand(pool,{accountId:id,actionId:randomUUID(),kind:'start',regionId:1,expectedRevision:2})).status,'applied');
  assert.equal((await train(2,{hp:1},3)).status,'busy');
  assert.equal((await applyExpeditionCommand(pool,{accountId:id,actionId:randomUUID(),kind:'stop',expectedRevision:3})).status,'applied');
  assert.equal((await reserveEncounter(pool,{accountId:id,actionId:randomUUID(),regionId:1,expectedRevision:4})).status,'reserved');
  assert.equal((await train(2,{hp:1},5)).status,'busy');
  const receipts=await pool.query("SELECT count(*)::int AS n FROM game_action_receipts WHERE account_id=$1 AND kind='pokemon-training'",[id]);
  assert.equal(receipts.rows[0].n,1);
 }finally{if(id)await pool.query('DELETE FROM game_accounts WHERE id=$1',[id]);await pool.end();}
});
